/// 4px Grid Spacing System for Galerisinden Tycoon
class AppSpacing {
  AppSpacing._();

  /// 4px — Micro spacing (icon-text tight, badge padding)
  static const double xs = 4.0;

  /// 8px — Small spacing (component internal padding, tight lists)
  static const double sm = 8.0;

  /// 12px — Medium spacing (card padding, grid gaps)
  static const double md = 12.0;

  /// 16px — Large spacing (card margins, screen padding)
  static const double lg = 16.0;

  /// 24px — Extra Large spacing (section spacing)
  static const double xl = 24.0;

  /// 32px — Double Extra Large spacing (major screen sections)
  static const double xxl = 32.0;

  /// 48px — Hero / Screen edge spacing
  static const double xxxl = 48.0;
}
